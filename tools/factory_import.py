"""Replace one factory preset from a .wt2 file and regenerate the C table and the editor list.

    python3 tools/factory_import.py <slot> <file.wt2> <name>

<slot> is the factory number on the device and in the editor: 1 is F01 (init), 9 is F09.
<name> is the patch name, lowercase, at most 11 characters (the device name limit): letters, digits, hyphen.

The .wt2 is copied to factory/NN-<name>.wt2. Every factory/NN-*.wt2 is then written into
core/wt_factory_gen.inc (a full 206-value overlay, so the result does not depend on the
hand-written base patches). The name list in core/wt_patch.c and web/app.js is updated to match.

WT-2 and WT-1 builds use different names for five of the same parameter slots. Each of those
is emitted under both names so the numeric value is identical in both builds:

    UNI_TOP/DR_KIT  CH_DEPTH/DR_LEVEL  HYPER/DR_DIST  CH_MIX/SC_AMT  CH_RATE/SC_REL

Rebuild after import: VARIANT=wt2 ./build-fw.sh  and  ./web/build-wt2.sh
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FACTORY = ROOT / "factory"
GEN = ROOT / "core" / "wt_factory_gen.inc"
PATCH_C = ROOT / "core" / "wt_patch.c"
APP_JS = ROOT / "web" / "app.js"
N = 11
NAME_RE = re.compile(r"^[a-z0-9-]{1,11}$")
ALIASES = {
    "UNI_TOP": "DR_KIT", "DR_KIT": "UNI_TOP",
    "CH_DEPTH": "DR_LEVEL", "DR_LEVEL": "CH_DEPTH",
    "HYPER": "DR_DIST", "DR_DIST": "HYPER",
    "CH_MIX": "SC_AMT", "SC_AMT": "CH_MIX",
    "CH_RATE": "SC_REL", "SC_REL": "CH_RATE",
}


def die(msg):
    print("factory_import: " + msg, file=sys.stderr)
    sys.exit(1)


def read_names():
    text = PATCH_C.read_text()
    m = re.search(r'wt_patch_names\[WT_NPATCHES\] = \{([^}]+)\}', text)
    if not m:
        die("could not find wt_patch_names in " + str(PATCH_C))
    return re.findall(r'"([^"]*)"', m.group(1))


def load_wt2(path):
    try:
        doc = json.loads(Path(path).read_text())
    except (OSError, json.JSONDecodeError) as e:
        die(str(e))
    if doc.get("format") != "wt2-patch":
        die(path + " is not a wt2-patch file")
    params = doc.get("params")
    if not isinstance(params, dict) or len(params) != 206:
        die(path + " has %s parameters, want 206" % (len(params) if isinstance(params, dict) else "no"))
    for k, v in params.items():
        if isinstance(v, bool) or not isinstance(v, int):
            die("%s.%s is not an integer" % (path, k))
    return doc


def emit_pairs(params):
    seen = set()
    out = []
    for k, v in params.items():
        if k not in seen:
            out.append((k, v))
            seen.add(k)
        alt = ALIASES.get(k)
        if alt and alt not in seen and alt not in params:
            out.append((alt, v))
            seen.add(alt)
    return out


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_gen(slots):
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only",
        " * Generated by tools/factory_import.py from the factory directory. Do not edit. */",
    ]
    for idx in sorted(slots):
        lines.append("static const kv factory_gen_%d[] = {" % idx)
        for n, v in slots[idx]:
            lines.append("    {%s, %s}," % (c_string(n), c_string(str(v))))
        lines.append("    {0, 0}};")
    lines.append("static const kv *factory_gen(int i)")
    lines.append("{")
    lines.append("    switch (i) {")
    for idx in sorted(slots):
        lines.append("    case %d: return factory_gen_%d;" % (idx, idx))
    lines.append("    default: return 0;")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    GEN.write_text("\n".join(lines))


def write_names(names):
    body = ", ".join('"%s"' % n for n in names)
    text = PATCH_C.read_text()
    new, k = re.subn(
        r'(wt_patch_names\[WT_NPATCHES\] = \{)[^}]+(\})',
        r'\1' + body + r'\2',
        text,
        count=1,
    )
    if k != 1:
        die("could not update wt_patch_names")
    PATCH_C.write_text(new)
    if not APP_JS.exists():
        return  # no editor in this tree
    js = APP_JS.read_text()
    js2, k = re.subn(
        r'(const PATCHES = \[)[^\]]+(\])',
        r'\1' + body + r'\2',
        js,
        count=1,
    )
    if k != 1:
        die("could not update PATCHES in web/app.js")
    APP_JS.write_text(js2)


def imported_slots():
    slots = {}
    if not FACTORY.is_dir():
        return slots
    for path in sorted(FACTORY.glob("*.wt2")):
        m = re.match(r"(\d+)-", path.name)
        if not m:
            continue
        idx = int(m.group(1)) - 1
        if not 0 <= idx < N:
            die("factory file %s is outside slots 1..%d" % (path.name, N))
        doc = load_wt2(path)
        slots[idx] = emit_pairs(doc["params"])
    return slots


def main():
    if len(sys.argv) != 4:
        die("usage: tools/factory_import.py <slot 1..%d> <file.wt2> <name>" % N)
    slot_s, src, name = sys.argv[1:]
    if not slot_s.isdigit() or not 1 <= int(slot_s) <= N:
        die("slot must be 1..%d (F%02d style)" % (N, N))
    slot = int(slot_s)
    if not NAME_RE.match(name):
        die("name %r must be lowercase, 1..11 characters, letters digits or hyphen" % name)
    doc = load_wt2(src)
    doc["name"] = name
    FACTORY.mkdir(exist_ok=True)
    for old in FACTORY.glob("%02d-*.wt2" % slot):
        old.unlink()
    dest = FACTORY / ("%02d-%s.wt2" % (slot, name))
    dest.write_text(json.dumps(doc, indent=2) + "\n")
    if Path(src).resolve() != dest.resolve():
        pass
    names = read_names()
    if len(names) != N:
        die("expected %d factory names, found %d" % (N, len(names)))
    names[slot - 1] = name
    write_names(names)
    write_gen(imported_slots())
    print("F%02d is now %s (%d parameters) -> %s" % (slot, name, len(doc["params"]), dest.relative_to(ROOT)))


if __name__ == "__main__":
    main()
