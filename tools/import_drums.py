#!/usr/bin/env python3 -I
"""One-off import of X0X's 909 / 808 drum engines (GPL-3.0) into core/drums/, adapted for WT-1:
  - the 909's hi-hat / ride / crash PCM stored as 8-bit mu-law (half the flash), decoded through a 256-entry table;
  - the engines' own pot-curve tables renamed (dr_pot_exp) so they sit beside the effects' tables;
  - the tanh table is the effects' one (fx_tables.h).
Run from WT-1:  python3 -I tools/import_drums.py  (reads ../M-vave Firmware/MODS/fm1-x0x-smk37)"""
import re, sys, math, struct, pathlib
here = pathlib.Path(__file__).resolve().parents[1]
x0x = here.parent / 'M-vave Firmware' / 'MODS' / 'fm1-x0x-smk37'
dsp = x0x / 'firmware' / 'src' / 'dsp'
out = here / 'core' / 'drums'
out.mkdir(exist_ok=True)
for f in ('drum909.c', 'drum909.h', 'drum909_dsp.h', 'drum808.c', 'drum808.h', 'x0x_param.h'):
    s = (dsp / f).read_text()
    s = s.replace('x0x_pot_exp', 'dr_pot_exp').replace('X0X_EXP_', 'DR_EXP_')
    s = s.replace('#include "x0x_drum_tables.h"', '#include "../fx_tables.h"\n#include "dr_tables.h"')
    s = s.replace('#include "fastmath.h"', '#include "../fastmath.h"')
    s = s.replace('#define X0X_DRUM_TABLES_DEFINE              /* the shared lookup tables live here (x0x_drum_tables.h) */\n', '')
    s = s.replace('#include "x0x_drum_samples.h"', '#include "dr_samples.h"')
    if f == 'drum909.c':
        s = s.replace('s->buf = x0x_smp_crash; s->len = X0X_SMP_CRASH_LEN;', 's->buf = dr_smp_crash; s->len = DR_SMP_CRASH_LEN;')
        s = s.replace('s->buf = x0x_smp_ride; s->len = X0X_SMP_RIDE_LEN;', 's->buf = dr_smp_ride; s->len = DR_SMP_RIDE_LEN;')
        s = s.replace('s->buf = x0x_smp_hh; s->len = X0X_SMP_HH_LEN;', 's->buf = dr_smp_hh; s->len = DR_SMP_HH_LEN;')
        s = s.replace('const int16_t *buf = s->buf;', 'const uint8_t *buf = s->buf;')
        s = s.replace('(float)buf[s->pos] * (1.0f / 32768.0f)', '(float)dr_ulaw[buf[s->pos]] * (1.0f / 32768.0f)')
        s = s.replace('(float)buf[s->pos + 1] * (1.0f / 32768.0f)', '(float)dr_ulaw[buf[s->pos + 1]] * (1.0f / 32768.0f)')
    if f == 'drum909.h':
        s = s.replace('const int16_t *buf;', 'const uint8_t *buf;           /* mu-law (dr_ulaw) */')
    if f == 'drum808.c':
        s = s.replace('b.i += (int32_t)n << 23;', 'b.i += n * 8388608;   /* (WT-1: n << 23 with a negative n is undefined; same value) */')
    if f == 'drum909_dsp.h':
        s = '/* The 909 engine\'s DSP building blocks are the effects\' (fx_dsp.h): the same code, ported from the same source. */\n#pragma once\n#include "../fx_dsp.h"\n#include "dr_tables.h"\n'
    (out / f).write_text(s)

# samples -> mu-law
def read_wav(path):
    d = path.read_bytes(); i, ch, bits, data = 12, 1, 16, None
    while i + 8 <= len(d):
        cid, sz = d[i:i + 4], struct.unpack('<I', d[i + 4:i + 8])[0]
        if cid == b'fmt ':
            ch, bits = struct.unpack('<H', d[i + 10:i + 12])[0], struct.unpack('<H', d[i + 22:i + 24])[0]
        elif cid == b'data':
            data = d[i + 8:i + 8 + sz]; break
        i += 8 + sz + (sz & 1)
    bp = bits // 8 * ch; v = []
    for k in range(len(data) // bp):
        p = data[k * bp:k * bp + bits // 8]
        if bits == 16: x = struct.unpack('<h', p)[0]
        else: x = max(-32768, min(32767, int(math.floor(int.from_bytes(p, 'little', signed=True) / 256.0 + 0.5))))
        v.append(x)
    return v
def ulaw_enc(x):
    BIAS, CLIP = 0x84, 32635
    s = 0x80 if x < 0 else 0
    if x < 0: x = -x
    if x > CLIP: x = CLIP
    x += BIAS
    e = 7
    m = 0x4000
    while e > 0 and not (x & m): e -= 1; m >>= 1
    return (~(s | (e << 4) | ((x >> (e + 3)) & 0x0F))) & 0xFF
def ulaw_dec(u):
    u = ~u & 0xFF
    t = (((u & 0x0F) << 3) + 0x84) << ((u & 0x70) >> 4)
    return (0x84 - t) if (u & 0x80) else (t - 0x84)
h = ['/* Generated by tools/import_drums.py -- do not edit. The 909 hi-hat, ride and crash (ER-99, Matthew Cieplak, via 9W9, GPL-3.0),',
     ' * mono 44.1 kHz, 8-bit mu-law; dr_ulaw[] decodes a byte to int16. */', '#pragma once', '#include <stdint.h>', '']
c = ['/* Generated by tools/import_drums.py -- do not edit. */', '#include "dr_samples.h"', '']
dec = [ulaw_dec(u) for u in range(256)]
c.append('const int16_t dr_ulaw[256] = {\n    ' + ',\n    '.join(', '.join(str(v) for v in dec[i:i + 16]) for i in range(0, 256, 16)) + ',\n};')
h.append('extern const int16_t dr_ulaw[256];')
tot = 0
for nm, fn in (('hh', 'hh.wav'), ('ride', 'ride.wav'), ('crash', 'crash.wav')):
    pcm = read_wav(x0x / 'assets' / '909' / fn); tot += len(pcm)
    h.append('#define DR_SMP_%s_LEN %du' % (nm.upper(), len(pcm)))
    h.append('extern const uint8_t dr_smp_%s[%d];' % (nm, len(pcm)))
    b = [ulaw_enc(x) for x in pcm]
    c.append('const uint8_t dr_smp_%s[%d] = {\n    ' % (nm, len(pcm)) + ',\n    '.join(', '.join(str(v) for v in b[i:i + 24]) for i in range(0, len(b), 24)) + ',\n};')
(out / 'dr_samples.h').write_text('\n'.join(h) + '\n')
(out / 'dr_samples.c').write_text('\n'.join(c) + '\n')
# pot tables, from the X0X generated header (renamed, tanh dropped: the effects have it)
t = (x0x / 'build' / 'gen' / 'x0x_drum_tables.h').read_text()
m = re.search(r'(#define X0X_EXP_BD_DECAY.*?#define X0X_EXP_COUNT 19)', t, re.S)
defs = m.group(1).replace('X0X_EXP_', 'DR_EXP_')
body = re.search(r'const float x0x_pot_exp\[19\]\[128\] = \{(.*?)\n\};', t, re.S).group(1)
(out / 'dr_tables.h').write_text('/* The 909 / 808 engines\' pot curves (9W9 er99_pots.h), generated: value = min * (max/min)^(pot/127). */\n#pragma once\n' + defs + '\nextern const float dr_pot_exp[19][128];\n')
(out / 'dr_tables.c').write_text('#include "dr_tables.h"\nconst float dr_pot_exp[19][128] = {' + body + '\n};\n')
print('samples', tot, 'frames; wrote', sorted(p.name for p in out.iterdir()))
